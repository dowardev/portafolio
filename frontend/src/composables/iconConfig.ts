export function getIconsByType(type: IconType | "all"): IconConfig[] {
  if (type === "all") return allIcons;
  return allIcons.filter((icon) => icon.type === type);
}

export function getIconByName(name: string): IconConfig | undefined {
  return allIcons.find((icon) => icon.name === name);
}

export function getIconColor(name: string): string {
  const icon = getIconByName(name);
  return icon?.color || "#666666";
}