export const allLineIcons: LineIconConfig[] = [...lineIconsTech, ...lineIconsSocial];

export function getLineIconsByType(type: IconType | "all"): LineIconConfig[] {
  if (type === "all") return allLineIcons;
  return allLineIcons.filter((icon) => icon.type === type);
}

export function getLineIconByName(name: string): LineIconConfig | undefined {
  return allLineIcons.find((icon) => icon.name === name);
}

export function getLineIconColor(name: string): string {
  const icon = getLineIconByName(name);
  return icon?.color || "#666666";
}

export function searchLineIcons(query: string): LineIconConfig[] {
  const search = query.toLowerCase();
  return allLineIcons.filter(
    (icon) =>
      icon.label.toLowerCase().includes(search) ||
      icon.name.toLowerCase().includes(search)
  );
}